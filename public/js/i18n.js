const MAIN_TROOPS = ['infantry', 'cavalry', 'archer', 'mage'];

let currentLang = localStorage.getItem('cod_lang') || 'en';

function t(key, params = {}) {
  const str = I18N[currentLang]?.[key] || I18N.en[key] || key;
  return str.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

function fieldLabel(field) {
  return t(field) || field;
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('cod_lang', lang);
  document.documentElement.lang = lang;
  window.dispatchEvent(new Event('languagechange'));
}

function getMainLabel(value) {
  if (!value) return '-';
  const key = `main_${value}`;
  return t(key) || value;
}

function getMainOptions() {
  return MAIN_TROOPS.map(v => ({ value: v, label: t(`main_${v}`) }));
}

function renderLanguageSelector() {
  return `
    <div class="lang-selector">
      <select id="lang-select" onchange="setLanguage(this.value); location.reload()">
        <option value="vi" ${currentLang === 'vi' ? 'selected' : ''}>VI — Tiếng Việt</option>
        <option value="en" ${currentLang === 'en' ? 'selected' : ''}>EN — English</option>
        <option value="ko" ${currentLang === 'ko' ? 'selected' : ''}>KO — 한국어</option>
      </select>
    </div>
  `;
}

function calcMP(merit, power) {
  const m = Number(merit) || 0;
  const p = Number(power) || 0;
  if (p <= 0) return 0;
  return (m / p) * 100;
}

function formatMP(merit, power) {
  const val = calcMP(merit, power);
  if (val === 0) return '-';
  return val.toFixed(2) + '%';
}
